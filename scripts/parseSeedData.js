function parseLines() {
  const lines = rawData.trim().split('\n').filter(Boolean);
  console.log(`Total lines read: ${lines.length}`);
  const items = [];
  const idCounts = {};

  for (const line of lines) {
    // Regex matching: S.NO MACHINE_TYPE MACHINE_MAKE M/C_NO YEAR LOCATION PLANT
    // Notice MACHINE_TYPE can be multiple words (e.g. S/N EDGE CUTTER, MINI TEMPLATE, RIP OVER LOCK, LFC O/L, SMALL FUSHING, etc.)
    // But location is NETHAJI, plant is UNIT - 1, year is 4 digits.
    // At the end: (\d{4})\s+(NETHAJI)\s+(UNIT\s*-\s*1)
    const match = line.match(/^(\d+)\s+(.+?)\s+([A-Z]+)\s+([^\s]+)\s+(\d{4})\s+(NETHAJI)\s+(UNIT\s*-\s*1)$/);
    if (!match) {
      console.error('Failed to parse line:', line);
      continue;
    }
    const [_, sNoStr, machineType, make, mcNo, yearStr, location, plant] = match;
    const sNo = parseInt(sNoStr, 10);
    const year = parseInt(yearStr, 10);

    // Track ID uniqueness
    idCounts[mcNo] = (idCounts[mcNo] || 0) + 1;
    const uniqueId = idCounts[mcNo] > 1 ? `${mcNo}-${idCounts[mcNo]}` : mcNo;

    // Capitalize make
    const brand = make.charAt(0).toUpperCase() + make.slice(1).toLowerCase();

    items.push({
      sNo,
      id: uniqueId,
      mcNo,
      name: `${brand} ${machineType}`,
      brand,
      model: machineType,
      category: 'MACHINE',
      department: 'Sewing Floor',
      type: machineType,
      typeName: machineType,
      purchaseDate: `${year}-01-01`,
      year,
      cost: 45000,
      status: 'ACTIVE',
      currentLine: `Line 0${((sNo - 1) % 8) + 1}`,
      stationNo: `Station ${((sNo - 1) % 24) + 1}`,
      unit: plant,
      area: location,
      company: 'Sahana Garments Ltd',
      totalDowntimeMinutes: 0,
      motorType: 'SERVO',
      specs: `Plant ${plant} • Location ${location} • Year ${year}`
    });
  }

  console.log(`Successfully parsed: ${items.length} items`);
  console.log(`First item:`, JSON.stringify(items[0], null, 2));
  console.log(`246th item:`, JSON.stringify(items[items.length - 1], null, 2));

  // Save to file only if not already containing full plant assets
  if (!fs.existsSync('src/data/plantAssetsSeed.json')) {
    fs.writeFileSync('src/data/plantAssetsSeed.json', JSON.stringify(items, null, 2));
    console.log('Saved to src/data/plantAssetsSeed.json');
  }
}

