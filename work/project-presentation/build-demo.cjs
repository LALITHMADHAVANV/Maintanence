const fs = require('node:fs');
const os = require('node:os');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('qrcode.react'), 'utf8');
const start = source.indexOf('// src/third-party/qrcodegen/index.ts');
const end = source.indexOf('var qrcodegen_default = qrcodegen;');
if (start < 0 || end < start) throw Error('QR encoder not found');
const encoder = source.slice(start, end);
const address = Object.values(os.networkInterfaces()).flat().find(n => n && n.family === 'IPv4' && !n.internal)?.address || '127.0.0.1';
const url = `http://${address}:3080/demo-qr.html#machine`;
const html = fs.readFileSync('work/project-presentation/demo-template.html', 'utf8').replace('/*__QR_ENCODER__*/', encoder).replace('/*__DEFAULT_URL__*/', url);
fs.writeFileSync('public/demo-qr.html', html);
fs.writeFileSync('docs/demo-qr.html', html);
const context = {};
vm.createContext(context);
vm.runInContext(encoder, context);
const code = context.qrcodegen.QrCode.encodeText(url, context.qrcodegen.QrCode.Ecc.MEDIUM);
const n = code.size + 8;
let path = '';
for (let y=0;y<code.size;y++) for(let x=0;x<code.size;x++) if(code.getModule(x,y)) path+=`M${x+4} ${y+4}h1v1h-1z`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 ${n} ${n}"><title>Demo machine QR: ${url}</title><rect width="${n}" height="${n}" fill="white"/><path d="${path}" fill="black"/></svg>`;
fs.writeFileSync('docs/demo-machine-qr.svg', svg);
fs.writeFileSync('public/demo-machine-qr.svg', svg);
fs.writeFileSync('work/project-presentation/demo-target.json',JSON.stringify({url,address},null,2));
console.log('Created HTML and machine QR. Target: '+url);
